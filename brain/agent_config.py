"""Versioned immutable configuration reader and dashboard v2 publication contract."""

from datetime import time
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from .voice_catalog import profile


class ClinicProfile(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    address_en: str | None = Field(default=None, max_length=2000)
    address_ur: str | None = Field(default=None, max_length=2000)
    preparation_en: str | None = Field(default=None, max_length=4000)
    preparation_ur: str | None = Field(default=None, max_length=4000)


class AgentSettings(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    name: str = Field(default="Synthetic Receptionist", min_length=1, max_length=100)
    language_mode: Literal["en", "ur", "bilingual"] = "bilingual"
    instructions: str = Field(default="Ask one question at a time.", min_length=1, max_length=2000)
    read_digits_in_english: bool = False
    prayer_break: list[str] | None = Field(default=None, min_length=2, max_length=2)
    clinic_profile: ClinicProfile = Field(default_factory=ClinicProfile)

    @field_validator("prayer_break")
    @classmethod
    def valid_prayer_break(cls, value):
        if value is not None:
            try:
                first, last = map(time.fromisoformat, value)
                if first.tzinfo or last.tzinfo or first >= last:
                    raise ValueError()
            except ValueError:
                raise ValueError("Prayer break requires ordered local wall times") from None
        return value


class LegacyAgentConfig(AgentSettings):
    schema_version: Literal[1] = 1


class AgentConfig(AgentSettings):
    schema_version: Literal[2] = 2
    greeting_en: str = Field(default="Hello. How can I help you today?", max_length=500)
    greeting_ur: str = Field(default="السلام علیکم۔ آپ کیسے ہیں؟", max_length=500)
    tone: Literal["friendly", "formal", "concise"] = "friendly"
    voice_en_id: str = "kokoro-af-heart-v1"
    voice_ur_id: str = "parler-ur-female-v1"
    voice_profiles: dict[str, dict] = Field(default_factory=dict)

    @model_validator(mode="after")
    def complete(self):
        required = ["en", "ur"] if self.language_mode == "bilingual" else [self.language_mode]
        for language in required:
            if not getattr(self, "greeting_" + language).strip():
                raise ValueError("Greeting required for selected language")
        en, ur = profile(self.voice_en_id), profile(self.voice_ur_id)
        if en["language"] != "en" or ur["language"] != "ur":
            raise ValueError("Voice language does not match selection")
        if self.language_mode == "bilingual" and en["gender"] != ur["gender"]:
            raise ValueError("Bilingual voices must have matching gender")
        expected = {"en": en, "ur": ur}
        if self.voice_profiles and self.voice_profiles != expected:
            raise ValueError("Voice profile snapshot does not match frozen catalog")
        self.voice_profiles = expected
        return self


def read_config(value: dict) -> LegacyAgentConfig | AgentConfig:
    return (
        AgentConfig.model_validate(value)
        if value.get("schema_version", 1) == 2
        else LegacyAgentConfig.model_validate(value)
    )


def greeting(value: dict, language: str) -> str:
    """Disclosure is always generated by code, regardless of editable greetings."""
    config = read_config(value)
    disclosure = {
        "en": "I am an AI scheduling assistant.",
        "ur": "میں اے آئی اپوائنٹمنٹ معاون ہوں۔",
    }[language]
    custom = getattr(
        config,
        "greeting_" + language,
        {"en": "Hello. How can I help you today?", "ur": "السلام علیکم۔ آپ کیسے ہیں؟"}[language],
    )
    return disclosure + " " + custom
